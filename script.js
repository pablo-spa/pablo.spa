const toggle = document.querySelector(".language-toggle");
const nodes = document.querySelectorAll("[data-i18n]");
let language = ["en", "de", "es"].includes(document.documentElement.lang) ? document.documentElement.lang : "en";

function setLanguage(next) {
  language = next;
  document.documentElement.lang = next;
  document.title = copy[next].title;
  document.querySelector('meta[name="description"]').content = copy[next].description;
  document.querySelector('meta[property="og:title"]').content = copy[next].title;
  document.querySelector('meta[property="og:description"]').content = copy[next].description;
  document.querySelector('meta[name="twitter:title"]').content = copy[next].title;
  document.querySelector('meta[name="twitter:description"]').content = copy[next].description;
  nodes.forEach((node) => {
    const value = copy[next][node.dataset.i18n];
    if (value) node.innerHTML = value;
  });
  document.querySelectorAll("[data-i18n-alt]").forEach((node) => {
    const value = copy[next][node.dataset.i18nAlt];
    if (value) node.alt = value;
  });
  const nextLanguage = { en: "de", de: "es", es: "en" }[next];
  toggle.innerHTML = `${nextLanguage.toUpperCase()} <span>↗</span>`;
  const switchLabel = {
    en: { de: "Switch to German" },
    de: { es: "Zu Spanisch wechseln" },
    es: { en: "Cambiar a inglés" }
  };
  toggle.setAttribute("aria-label", switchLabel[next][nextLanguage]);
}

toggle.addEventListener("click", () => setLanguage({ en: "de", de: "es", es: "en" }[language]));
setLanguage(language);

const revealItems = document.querySelectorAll(".reveal");
if ("IntersectionObserver" in window && !window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
  const observer = new IntersectionObserver((entries, currentObserver) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("is-visible");
        currentObserver.unobserve(entry.target);
      }
    });
  }, { threshold: 0.12, rootMargin: "0px 0px -32px 0px" });
  revealItems.forEach((item) => observer.observe(item));
} else {
  revealItems.forEach((item) => item.classList.add("is-visible"));
}
